/**
 * Migrate + optimize the Supabase Storage `media` bucket into /public/images/media.
 *
 * - Downloads every image from the `media` bucket.
 * - Resizes (max 1600px) + converts to WebP (≈90% smaller).
 * - Writes them to public/images/media/ (served free + cached by Cloudflare Pages).
 * - Emits src/lib/media-manifest.ts mapping each original storage key → local file,
 *   which the middleware uses to rewrite URLs. Files NOT in the manifest (PDFs,
 *   future uploads) keep falling back to the /cdn/media proxy.
 *
 * Non-image files (PDFs) are skipped — they stay on Supabase via the proxy.
 * SVG/GIF are copied as-is (not re-encoded).
 *
 * Usage: node --env-file=.env scripts/migrate-media-to-public.mjs
 */
import { createClient } from '@supabase/supabase-js';
import sharp from 'sharp';
import { mkdirSync, writeFileSync, existsSync } from 'fs';
import { join, extname } from 'path';

const SUPABASE_URL = process.env.PUBLIC_SUPABASE_URL;
const sb = createClient(SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

const OUT_DIR = 'public/images/media';
const MAX_WIDTH = 1600;
const WEBP_QUALITY = 80;
const CONVERTIBLE = ['.png', '.jpg', '.jpeg'];
const COPY_AS_IS = ['.svg', '.gif', '.webp', '.avif']; // already web-optimized formats

mkdirSync(OUT_DIR, { recursive: true });

async function listAll(prefix = '') {
  let all = [];
  let offset = 0;
  while (true) {
    const { data, error } = await sb.storage.from('media').list(prefix, {
      limit: 100, offset, sortBy: { column: 'name', order: 'asc' },
    });
    if (error) { console.error('list error', prefix, error.message); break; }
    if (!data || data.length === 0) break;
    for (const item of data) {
      const key = prefix ? `${prefix}/${item.name}` : item.name;
      if (item.id === null || item.metadata == null) {
        all = all.concat(await listAll(key)); // folder
      } else {
        all.push({ key, size: item.metadata?.size || 0 });
      }
    }
    offset += data.length;
    if (data.length < 100) break;
  }
  return all;
}

function localNameFor(key) {
  // Flatten any subfolders into the filename to keep /public/images/media flat.
  const flat = key.replace(/\//g, '__');
  const ext = extname(flat).toLowerCase();
  if (CONVERTIBLE.includes(ext)) return flat.replace(/\.(png|jpe?g)$/i, '.webp');
  return flat; // svg/gif copied as-is
}

const files = await listAll();
console.log(`Found ${files.length} files in media bucket.`);

const manifest = {};
let before = 0, after = 0, converted = 0, copied = 0, skipped = 0;

for (const { key, size } of files) {
  const ext = extname(key).toLowerCase();
  const isConvertible = CONVERTIBLE.includes(ext);
  const isCopy = COPY_AS_IS.includes(ext);
  if (!isConvertible && !isCopy) { skipped++; continue; } // PDFs etc → proxy fallback

  const localName = localNameFor(key);
  const outPath = join(OUT_DIR, localName);

  try {
    const { data, error } = await sb.storage.from('media').download(key);
    if (error || !data) { console.error('  download fail', key, error?.message); skipped++; continue; }
    const buf = Buffer.from(await data.arrayBuffer());
    before += buf.length;

    if (isConvertible) {
      const meta = await sharp(buf).metadata();
      const width = Math.min(meta.width || MAX_WIDTH, MAX_WIDTH);
      const out = await sharp(buf)
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: WEBP_QUALITY })
        .toBuffer();
      writeFileSync(outPath, out);
      after += out.length;
      converted++;
      console.log(`  ✓ ${key}  ${(buf.length/1024).toFixed(0)}KB → ${(out.length/1024).toFixed(0)}KB webp`);
    } else {
      writeFileSync(outPath, buf);
      after += buf.length;
      copied++;
      console.log(`  • ${key}  copied as-is (${(buf.length/1024).toFixed(0)}KB)`);
    }
    manifest[key] = localName;
  } catch (e) {
    console.error('  error', key, e.message);
    skipped++;
  }
}

// Emit the manifest module.
const ts = `// AUTO-GENERATED by scripts/migrate-media-to-public.mjs — do not edit by hand.
// Maps a Supabase Storage \`media\` bucket key → its optimized local file under /images/media/.
// Used by src/middleware.ts to rewrite Supabase media URLs to free Cloudflare-served assets.
export const MEDIA_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync('src/lib/media-manifest.ts', ts);

console.log(`\nDone. converted=${converted} copied=${copied} skipped(non-image/pdf)=${skipped}`);
console.log(`Total: ${(before/1e6).toFixed(1)} MB → ${(after/1e6).toFixed(1)} MB  (${(100*(1-after/before)).toFixed(0)}% smaller)`);
console.log(`Manifest entries: ${Object.keys(manifest).length} → src/lib/media-manifest.ts`);
